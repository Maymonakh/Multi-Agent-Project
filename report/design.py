"""Everything the report agent can change: page, fonts, colors, spacing, header/footer, cover."""
from pydantic import BaseModel, Field

ROLES = ["title", "subtitle", "h1", "h2", "h3", "body", "table", "caption"]
COLOR_KEYS = ["primary", "secondary", "text", "accent", "table_header", "table_stripe", "rule"]
PAGE_SIZES = ["A4", "A3", "LETTER", "LEGAL"]


class FontStyle(BaseModel):
    family: str = "Helvetica"
    size: float = 10.5
    bold: bool = False
    italic: bool = False
    color: str | None = None        # None = use the theme color of that role


class Design(BaseModel):
    page_size: str = "A4"
    orientation: str = "portrait"
    margin_cm: float = 2.0
    columns: int = 1
    line_height: float = 1.35       # multiplier of the font size
    paragraph_spacing: float = 6    # points after a paragraph
    section_spacing: float = 14     # points before a heading
    body_align: str = "left"
    header_text: str = ""
    footer_text: str = ""
    page_numbers: bool = True
    cover_page: bool = False
    cover_title: str = ""
    cover_subtitle: str = ""
    author: str = ""
    colors: dict[str, str] = Field(default_factory=dict)
    fonts: dict[str, FontStyle] = Field(default_factory=dict)


def _fonts(family: str, title: float, h1: float, h2: float, h3: float, body: float) -> dict:
    return {
        "title": FontStyle(family=family, size=title, bold=True),
        "subtitle": FontStyle(family=family, size=body + 3, italic=True),
        "h1": FontStyle(family=family, size=h1, bold=True),
        "h2": FontStyle(family=family, size=h2, bold=True),
        "h3": FontStyle(family=family, size=h3, bold=True),
        "body": FontStyle(family=family, size=body),
        "table": FontStyle(family=family, size=body - 1),
        "caption": FontStyle(family=family, size=body - 2, italic=True),
    }


PRESETS = {
    "professional": lambda: Design(
        fonts=_fonts("Helvetica", 24, 16, 13, 11, 10.5),
        colors={"primary": "#1F3A5F", "secondary": "#4A6FA5", "text": "#222222", "accent": "#E07A1F",
                "table_header": "#1F3A5F", "table_stripe": "#EEF2F7", "rule": "#C9D3E0"},
        footer_text="Generated by the Multi-Agent RAG system"),
    "classic": lambda: Design(
        body_align="justify", line_height=1.4,
        fonts=_fonts("Times", 22, 16, 13, 12, 11.5),
        colors={"primary": "#111111", "secondary": "#555555", "text": "#111111", "accent": "#8B0000",
                "table_header": "#333333", "table_stripe": "#F2F2F2", "rule": "#999999"}),
    "modern": lambda: Design(
        cover_page=True, section_spacing=18, paragraph_spacing=8,
        fonts=_fonts("Helvetica", 28, 18, 14, 12, 10.5),
        colors={"primary": "#0F766E", "secondary": "#475569", "text": "#1E293B", "accent": "#F59E0B",
                "table_header": "#0F766E", "table_stripe": "#ECFDF5", "rule": "#99F6E4"},
        footer_text="Generated by the Multi-Agent RAG system"),
}


def get_preset(name: str) -> Design:
    return PRESETS.get((name or "").lower(), PRESETS["professional"])()
